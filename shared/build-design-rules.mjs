import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const srcPath = resolve(root, 'shared/design-rules/design-rules.src.md');

const targets = [
  { variant: 'base', out: 'plugins/infographic/skills/infographic/references/design-rules.md' },
  { variant: 'gov', out: 'plugins/gov-doc-infographic/skills/gov-doc-infographic/references/design-rules.md' },
];

export function derive(src, variant) {
  const drop = variant === 'gov' ? 'base-only' : 'gov-only';
  const keep = variant === 'gov' ? 'gov-only' : 'base-only';
  const lines = src.replace(/\r\n/g, '\n').split('\n');
  const out = [];
  let skipping = false;
  for (const line of lines) {
    const t = line.trim();
    if (t === `<!-- ${drop} -->`) { skipping = true; continue; }
    if (t === `<!-- /${drop} -->`) { skipping = false; continue; }
    if (t === `<!-- ${keep} -->` || t === `<!-- /${keep} -->`) continue;
    if (!skipping) out.push(line);
  }
  const header = `<!-- generated by shared/build-design-rules.mjs from shared/design-rules/design-rules.src.md (variant: ${variant}); edit the source, not this copy -->`;
  out.splice(1, 0, header);
  return out.join('\n').replace(/\n{3,}/g, '\n\n').replace(/\n*$/, '\n');
}

const src = readFileSync(srcPath, 'utf8');
const check = process.argv.includes('--check');
let bad = 0;
for (const { variant, out } of targets) {
  const file = resolve(root, out);
  const want = derive(src, variant);
  if (check) {
    let have = null;
    try { have = readFileSync(file, 'utf8').replace(/\r\n/g, '\n'); } catch {}
    if (have !== want) { console.error(`MISMATCH ${out}`); bad++; } else console.log(`ok ${out}`);
  } else {
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, want, 'utf8');
    console.log(`wrote ${out}`);
  }
}
process.exit(bad ? 1 : 0);
